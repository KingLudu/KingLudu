/**
 * Pre-generated pool of 600+ unique, distinct names so that every bot encounter
 * gets a completely fresh and unique identity each time.
 */
function buildUniqueNamePool(): string[] {
  const pool: string[] = [];
  const seen = new Set<string>();

  // 1. Generate First + Last Name combinations
  for (const fn of REAL_BOT_FIRST_NAMES) {
    for (const ln of REAL_BOT_LAST_NAMES) {
      const full = `${fn} ${ln}`;
      if (!seen.has(full)) {
        seen.add(full);
        pool.push(full);
      }
      if (pool.length >= 750) break;
    }
    if (pool.length >= 750) break;
  }

  // Shuffle pool with Fisher-Yates
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool;
}

// 700+ pre-built unique name catalog
export const BOT_NAMES_CATALOG: string[] = buildUniqueNamePool();

// Keep track of recently used names across matches so bots don't repeat
let recentNamesCursor = Math.floor(Math.random() * 50);

/**
 * Generate a single unique bot player with a realistic name and photo avatar.
 */
export function generateRandomPlayer(idPrefix: string = 'player'): { id: string; name: string; avatarUrl: string } {
  // Move cursor to get next fresh name from 700+ pool
  const name = BOT_NAMES_CATALOG[recentNamesCursor % BOT_NAMES_CATALOG.length];
  recentNamesCursor = (recentNamesCursor + 1) % BOT_NAMES_CATALOG.length;

  const avatar = REAL_BOT_AVATARS[Math.floor(Math.random() * REAL_BOT_AVATARS.length)];
  const randomId = `${idPrefix}_${Date.now().toString(36)}_${Math.floor(1000 + Math.random() * 9000)}`;

  return {
    id: randomId,
    name,
    avatarUrl: avatar,
  };
}

/**
 * Function to generate N unique opponent bot players for a match session.
 * Always ensures completely different names each time.
 */
export function getRandomOpponents(count: number = 3): Array<{ id: string; name: string; avatarUrl: string }> {
  const results: Array<{ id: string; name: string; avatarUrl: string }> = [];
  const usedNames = new Set<string>();

  let attempts = 0;
  while (results.length < count && attempts < 200) {
    attempts++;
    const p = generateRandomPlayer(`opp_${results.length + 1}`);
    if (!usedNames.has(p.name)) {
      usedNames.add(p.name);
      results.push(p);
    }
  }

  return results;
}
